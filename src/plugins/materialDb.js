// 转换成带 id/price/minScale 的完整条目
export const MATERIALS = RAW.map(([name, tier, type, desc], i) => ({
  id: 'mtl_' + name,
  key: 'mtl_' + name,
  name,
  tier,
  tierName: TIER_NAME(tier),
  type,
  desc,
  price: MATERIAL_TIERS[tier].price,
  minScale: MATERIAL_TIERS[tier].scale
}))

export const materialCount = MATERIALS.length

export const materialByKey = key => MATERIALS.find(m => m.key === key)

// 按「类别 + 品级(1~11)」取一件核心材料：优先精确匹配，其次向上取，最贴近
export const tierMaterial = (types, tier) => {
  const t = Math.max(0, Math.min(10, (tier || 1) - 1))
  let pool = MATERIALS.filter(m => types.includes(m.type) && m.tier === t)
  if (!pool.length) pool = MATERIALS.filter(m => types.includes(m.type) && m.tier <= t).sort((a, b) => b.tier - a.tier)
  if (!pool.length) pool = MATERIALS.filter(m => types.includes(m.type)).sort((a, b) => Math.abs(a.tier - t) - Math.abs(b.tier - t))
  if (!pool.length) return MATERIALS[0] || null
  // 确定性选取：同「类别+品级」恒返回同一件，保证炼制预览与结算一致
  const seed = (types.join('|') + ':' + t).split('').reduce((a, c) => (a * 31 + c.charCodeAt(0)) | 0, 7)
  return pool[Math.abs(seed) % pool.length]
}
export const matNameOf = key => materialByKey(key)?.name || key
